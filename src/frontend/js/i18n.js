const ORDEM = { pt: 0, en: 1, es: 2 };

export function idioma() { return estado.idioma in ORDEM ? estado.idioma : 'pt'; }

/** Texto na língua atual. `vars` substitui {chave} no texto. */
export function t(chave, vars = {}) {
  const linha = TEXTOS[chave];
  if (!linha) return chave;
  const texto = linha[ORDEM[idioma()]] || linha[0];
  return texto.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

/** Faixa que avisa o alcance da tradução quando o idioma não é o português. */
export function avisoIdioma() {
  if (idioma() === 'pt') return '';
  return `<p class="ig-nota ig-aviso-idioma"><i class="ph ph-translate" aria-hidden="true"></i> ${t('aviso.parcial')}</p>`;
}

/** Aplica as traduções aos elementos estáticos do index.html. */
export function traduzirCasca() {
  document.documentElement.lang = { pt: 'pt-BR', en: 'en', es: 'es' }[idioma()];
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-titulo]').forEach(el => { el.title = t(el.dataset.i18nTitulo); });
}
